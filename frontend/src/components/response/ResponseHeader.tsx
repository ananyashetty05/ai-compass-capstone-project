/**
 * Attribution header for a provider response.
 *
 * The one job of this header is to keep two facts visible at a glance
 * without turning them into a card: the text belongs to the provider
 * model, and AI Compass chose the route. Anything that could be read as
 * "AI Compass wrote this" is deliberately absent.
 *
 * The metadata line is kept to a single run-on row (model · provider ·
 * latency · tokens · cost) so the response itself keeps the space.
 */
import { Check, Clipboard, Route } from 'lucide-react';
import { useCallback, useState } from 'react';

export interface ResponseHeaderProps {
  modelName: string;
  provider: string | null;
  /** Pre-formatted metadata fragments, already joined for display. */
  facts?: readonly string[];
  onCopy: () => void;
}

export function ResponseHeader({ modelName, provider, facts = [], onCopy }: ResponseHeaderProps) {
  const [copied, setCopied] = useState(false);

  const copy = useCallback(() => {
    onCopy();
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1600);
  }, [onCopy]);

  return (
    <header className="response-header">
      <div className="response-header-top">
        <div className="response-header-identity">
          <p className="response-header-label">Generated by</p>
          {/* The provider, not AI Compass, is named as the author. */}
          <p className="response-header-model">{modelName}</p>
          {provider ? <p className="response-header-provider">via {provider}</p> : null}
        </div>

        <div className="response-header-actions">
          <span className="response-header-badge">
            <Route aria-hidden="true" />
            Routed by AI Compass
          </span>
          <button type="button" className="response-header-copy" onClick={copy}>
            {copied ? <Check aria-hidden="true" /> : <Clipboard aria-hidden="true" />}
            {copied ? 'Copied' : 'Copy response'}
          </button>
        </div>
      </div>

      {facts.length > 0 ? (
        <p className="response-header-facts">
          {[modelName, ...facts].filter(Boolean).join(' · ')}
        </p>
      ) : null}
    </header>
  );
}
